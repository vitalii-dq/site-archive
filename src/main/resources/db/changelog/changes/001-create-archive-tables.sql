--changeset site-archive:001-create-archive-job
CREATE TABLE archive_job (
    id                 UUID          PRIMARY KEY,
    sitemap_url        VARCHAR(2048) NOT NULL,
    max_pages          INTEGER       NOT NULL CHECK (max_pages > 0),
    status             VARCHAR(32)   NOT NULL
        CHECK (status IN ('QUEUED', 'RUNNING', 'COMPLETED', 'COMPLETED_WITH_ERRORS', 'FAILED')),
    site_origin        VARCHAR(2048),
    sitemap_url_count  INTEGER,
    excluded_url_count INTEGER,
    error_summary      TEXT,
    archive_file       VARCHAR(512),
    archive_size_bytes BIGINT,
    -- How often a crash of the service or a fatal error stopped the job; see archive.worker.max-crashes-per-job.
    crash_count        INTEGER       NOT NULL DEFAULT 0 CHECK (crash_count >= 0),
    created_at         TIMESTAMPTZ   NOT NULL,
    started_at         TIMESTAMPTZ,
    finished_at        TIMESTAMPTZ,
    updated_at         TIMESTAMPTZ   NOT NULL,
    version            BIGINT        NOT NULL
);

-- Job claiming: oldest queued job first. Partial, so it stays small however many jobs have finished.
CREATE INDEX ix_archive_job_queued ON archive_job (created_at, id) WHERE status = 'QUEUED';

-- Job history, newest first.
CREATE INDEX ix_archive_job_history ON archive_job (created_at DESC, id DESC);
--rollback DROP TABLE archive_job;

--changeset site-archive:002-create-archive-page
CREATE TABLE archive_page (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    archive_job_id  UUID          NOT NULL REFERENCES archive_job (id) ON DELETE CASCADE,
    source_url      VARCHAR(2048) NOT NULL,
    status          VARCHAR(16)   NOT NULL CHECK (status IN ('PENDING', 'SUCCEEDED', 'FAILED')),
    attempts        INTEGER       NOT NULL DEFAULT 0,
    http_status     INTEGER,
    final_url       VARCHAR(2048),
    content_type    VARCHAR(255),
    file_name       VARCHAR(255),
    size_bytes      BIGINT,
    error_message   TEXT,
    last_attempt_at TIMESTAMPTZ,
    captured_at     TIMESTAMPTZ,
    created_at      TIMESTAMPTZ   NOT NULL,
    -- Re-processing a job can never create a second record for the same URL.
    CONSTRAINT uq_archive_page_job_source_url UNIQUE (archive_job_id, source_url)
);

-- Page listing by archive, optionally filtered by status, in capture order.
CREATE INDEX ix_archive_page_job_status ON archive_page (archive_job_id, status, id);
--rollback DROP TABLE archive_page;
